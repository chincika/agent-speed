#!/usr/bin/env python3
"""Copy the strings the task-score prototype uses from spec/strings.json into strings.js."""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
SOURCE = HERE.parent.parent / "strings.json"
TARGET = HERE / "strings.js"

PREFIXES = (
    "task.", "a11y.task.", "history.tasks.", "a11y.history.tasks.", "intel.", "work.", "time.", "title.",
    "phase.", "source.", "history.range.", "speed.value.", "a11y.orb.", "a11y.board", "a11y.agent.",
)
KEYS = (
    "agents.intel.hint", "privacy.taskScore", "unit.tokS", "dashboard.agents", "agents.context", "cost.glyph",
    "cost.unitPerSecond", "history.title", "history.allSources", "history.export", "history.privacy",
    "history.privacy.short", "history.analyzing", "list.separator", "effort.tooltip", "speed.tooltip",
    "boards.subCount", "boards.today", "boards.peak", "boards.moreGroups",
)


def main():
    table = json.loads(SOURCE.read_text(encoding="utf-8"))
    picked = {k: v for k, v in table.items()
              if not k.startswith("_") and (k.startswith(PREFIXES) or k in KEYS)}
    missing = [k for k in KEYS if k not in picked]
    if missing:
        raise SystemExit(f"missing keys: {missing}")
    body = json.dumps(picked, ensure_ascii=False, indent=1)
    TARGET.write_text("// Generated by gen_strings.py from spec/strings.json. Do not edit.\n"
                      f"window.TS_STRINGS = {body};\n", encoding="utf-8")
    print(f"{len(picked)} strings -> {TARGET.name}")


if __name__ == "__main__":
    main()
